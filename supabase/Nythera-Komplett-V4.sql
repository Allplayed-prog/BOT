update public.registrations
set discord_id = discord_user_id
where discord_id is null and discord_user_id is not null;

update public.registrations
set discord_user_id = discord_id
where discord_user_id is null and discord_id is not null;

alter table public.registrations alter column discord_user_id drop not null;

-- Unique indexes only when there are no duplicates.
do $$
begin
  if not exists (
    select 1 from public.registrations
    where discord_id is not null
    group by discord_id having count(*) > 1
  ) then
    create unique index if not exists registrations_discord_id_unique
      on public.registrations(discord_id) where discord_id is not null;
  end if;

  if not exists (
    select 1 from public.registrations
    where discord_user_id is not null
    group by discord_user_id having count(*) > 1
  ) then
    create unique index if not exists registrations_discord_user_id_unique
      on public.registrations(discord_user_id) where discord_user_id is not null;
  end if;
end $$;

