-- Diese beiden Hilfstabellen dürfen neu erstellt werden.
drop table if exists public.panel_notifications cascade;
drop table if exists public.panel_repairs cascade;

create table public.panel_repairs (
  id bigint generated by default as identity primary key,
  panel_id uuid not null references public.panels(id) on delete cascade,
  hour_number integer not null,
  repaired_by text not null,
  repaired_at timestamptz not null default now(),
  unique (panel_id, hour_number)
);

create table public.panel_notifications (
  id bigint generated by default as identity primary key,
  panel_id uuid not null references public.panels(id) on delete cascade,
  notification_key text not null unique,
  notification_type text not null,
  created_at timestamptz not null default now()
);

